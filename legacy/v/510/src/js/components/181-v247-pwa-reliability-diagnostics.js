/* ============================================================
   MediaFlow v247 — PWA Install Reliability + Diagnostics
   --------------------------------------------------------------------------
   - Keeps the v246 mobile/tablet PWA UX.
   - Explains native-install availability instead of presenting a dead control.
   - Adds an explicit PWA diagnostics runner and cache repair action.
   - Verifies the deployed manifest, worker, app-shell cache and every local
     app-shell URL so GitHub Pages path/deployment failures are visible.
   - Works with the v247 worker diagnostic/repair message API generated by
     scripts/pwa.py.
   ============================================================ */
const V247_RUNTIME_VERSION=247;
const V247_PWA_DIAGNOSTICS={running:false,lastRunAt:0,report:null,error:''};
const V247_PWA_TIMEOUT=9000;

function v247WithTimeout(promise,ms=V247_PWA_TIMEOUT,label='operation'){
  let timer=0;
  return Promise.race([
    Promise.resolve(promise),
    new Promise((_,reject)=>{timer=setTimeout(()=>reject(new Error(`${label} timed out`)),ms);})
  ]).finally(()=>clearTimeout(timer));
}

function v247PwaStateLabel(){
  if(v244PwaStandalone()||V244_PWA_STATE.installed)return {tone:'pass',text:'Installed'};
  if(V244_PWA_STATE.installPrompt)return {tone:'pass',text:'Ready to install'};
  if(!v244PwaSupported())return {tone:'fail',text:'Install unavailable'};
  if(V247_PWA_DIAGNOSTICS.running)return {tone:'info',text:'Testing PWA'};
  const report=V247_PWA_DIAGNOSTICS.report;
  if(report?.status==='fail')return {tone:'fail',text:'Needs attention'};
  if(report?.status==='warn')return {tone:'warn',text:'Checks passed with warnings'};
  if(report?.status==='pass')return {tone:'pass',text:'PWA checks passed'};
  return {tone:'info',text:'PWA registered'};
}

function v247PwaStatus(){
  if(!v244PwaSupported())return 'Install unavailable — MediaFlow must run over HTTPS or localhost.';
  if(V244_PWA_STATE.updateReady)return `MediaFlow v${V247_RUNTIME_VERSION} app update is ready. Reload the app to apply it.`;
  if(v244PwaStandalone()||V244_PWA_STATE.installed)return V244_PWA_STATE.offlineReady?'Installed · service worker active and app shell available.':'Installed as an app.';
  if(V244_PWA_STATE.installPrompt)return V244_PWA_STATE.offlineReady?'Ready to install · Chrome/browser native install prompt is available.':'Ready to install.';
  if(V247_PWA_DIAGNOSTICS.running)return 'Checking manifest, service worker, app-shell cache and deployed PWA assets…';
  if(V247_PWA_DIAGNOSTICS.report?.status==='fail')return `Install needs attention — ${V247_PWA_DIAGNOSTICS.report.summary||'one or more PWA checks failed'}.`;
  if(V244_PWA_STATE.error)return `PWA setup could not finish: ${String(V244_PWA_STATE.error)}`;
  if(V247_PWA_DIAGNOSTICS.report?.status==='pass')return 'PWA technical checks passed. If Chrome still does not show Install, reload once or use the browser Install app menu.';
  if(V247_PWA_DIAGNOSTICS.report?.status==='warn')return 'PWA core checks passed with warnings. Open PWA Diagnostics for the exact install/cache state.';
  if(V244_PWA_STATE.offlineReady)return 'PWA service worker is ready, but the browser has not exposed a native install prompt yet. Run PWA Test for the exact reason.';
  return 'Preparing installable app support…';
}

