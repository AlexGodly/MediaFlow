function v247AddCheck(report,label,status,detail){
  report.checks.push({label,status,detail:String(detail||'')});
  if(status==='fail')report.failures++;
  if(status==='warn')report.warnings++;
}

async function v247FetchProbe(url,kind='asset'){
  const absolute=new URL(url,document.baseURI).href;
  const controller=new AbortController();
  const timer=setTimeout(()=>controller.abort(),V247_PWA_TIMEOUT);
  try{
    const response=await fetch(absolute,{cache:'no-store',signal:controller.signal,credentials:'same-origin'});
    return {url,absolute,ok:!!response.ok,status:response.status,type:response.type,contentType:response.headers.get('content-type')||'',kind};
  }catch(err){
    return {url,absolute,ok:false,status:0,error:String(err?.message||err||'fetch failed'),kind};
  }finally{clearTimeout(timer);}
}

async function v247MapLimit(items,limit,fn){
  const out=new Array(items.length);let next=0;
  async function worker(){
    while(true){
      const i=next++;if(i>=items.length)return;
      try{out[i]=await fn(items[i],i);}catch(err){out[i]={url:items[i],ok:false,status:0,error:String(err?.message||err||'failed')};}
    }
  }
  await Promise.all(Array.from({length:Math.min(limit,items.length||1)},()=>worker()));
  return out;
}

function v247ResolveManifestUrl(value,manifestUrl){
  try{return new URL(String(value||''),manifestUrl).href;}catch(_){return '';}
}

async function v247WorkerMessage(worker,message,timeout=V247_PWA_TIMEOUT){
  if(!worker||typeof worker.postMessage!=='function')throw new Error('No compatible service worker is available');
  const channel=new MessageChannel();
  const result=new Promise((resolve,reject)=>{
    const timer=setTimeout(()=>reject(new Error('Service worker diagnostic response timed out')),timeout);
    channel.port1.onmessage=event=>{clearTimeout(timer);resolve(event.data||{});};
    channel.port1.onmessageerror=()=>{clearTimeout(timer);reject(new Error('Service worker diagnostic response failed'));};
  });
  worker.postMessage(message,[channel.port2]);
  return result;
}

async function v247GetRegistration(){
  let reg=V244_PWA_STATE.registration;
  if(reg)return reg;
  if(!v244PwaSupported())return null;
  if(!reg)reg=await v244RegisterPwa();
  if(!reg&&navigator.serviceWorker?.getRegistration)reg=await navigator.serviceWorker.getRegistration('./');
  if(reg)V244_PWA_STATE.registration=reg;
  return reg||null;
}

async function v247GetWorkerDiagnostics(reg){
  const worker=reg?.waiting||reg?.active||reg?.installing||navigator.serviceWorker?.controller;
  if(!worker)return null;
  try{return await v247WorkerMessage(worker,{type:'GET_DIAGNOSTICS'});}catch(err){return {unsupported:true,error:String(err?.message||err)};}
}

async function v247ManifestDiagnostics(report){
  const manifestUrl=new URL('manifest.json',document.baseURI).href;
  try{
    const response=await fetch(manifestUrl,{cache:'no-store'});
    if(!response.ok)throw new Error(`HTTP ${response.status}`);
    const manifest=await response.json();
    report.manifest=manifest;
    const hasName=!!(manifest.name||manifest.short_name);
    const start=v247ResolveManifestUrl(manifest.start_url,manifestUrl);
    const scope=v247ResolveManifestUrl(manifest.scope||'./',manifestUrl);
    const display=[manifest.display,...(Array.isArray(manifest.display_override)?manifest.display_override:[])].filter(Boolean);
    const installDisplay=display.some(x=>['standalone','minimal-ui','fullscreen','window-controls-overlay'].includes(x));
    const startInScope=!!start&&!!scope&&start.startsWith(scope);
    const icons=Array.isArray(manifest.icons)?manifest.icons:[];
    const icon192=icons.find(x=>String(x.sizes||'').split(/\s+/).includes('192x192'));
    const icon512=icons.find(x=>String(x.sizes||'').split(/\s+/).includes('512x512')&&String(x.purpose||'any').includes('any'))||icons.find(x=>String(x.sizes||'').split(/\s+/).includes('512x512'));
    const valid=hasName&&!!start&&!!scope&&installDisplay&&startInScope&&!!icon192&&!!icon512;
    v247AddCheck(report,'Web app manifest',valid?'pass':'fail',valid?`Loaded · ${manifest.short_name||manifest.name} · ${manifest.display||'display missing'}`:'Missing a required name/start_url/scope/display/192px/512px manifest field');
    if(icon192&&icon512){
      const probes=await Promise.all([v247FetchProbe(v247ResolveManifestUrl(icon192.src,manifestUrl),'icon'),v247FetchProbe(v247ResolveManifestUrl(icon512.src,manifestUrl),'icon')]);
      report.iconProbes=probes;
      const iconsOk=probes.every(x=>x.ok);
      v247AddCheck(report,'Install icons',iconsOk?'pass':'fail',iconsOk?'192×192 and 512×512 icons are reachable':probes.filter(x=>!x.ok).map(x=>`${x.url}: ${x.status||x.error}`).join(' · '));
    }
    if(!startInScope)v247AddCheck(report,'Manifest scope','fail',`start_url ${start||'missing'} is outside scope ${scope||'missing'}`);
    else v247AddCheck(report,'Manifest scope','pass',scope);
  }catch(err){
    v247AddCheck(report,'Web app manifest','fail',String(err?.message||err||'manifest failed'));
  }
}

async function v247RunPwaDiagnostics(options={}){
  if(V247_PWA_DIAGNOSTICS.running)return V247_PWA_DIAGNOSTICS.report;
  V247_PWA_DIAGNOSTICS.running=true;
  V247_PWA_DIAGNOSTICS.error='';
  v244RefreshPwaDom();
  const report={status:'pass',summary:'',startedAt:Date.now(),finishedAt:0,checks:[],failures:0,warnings:0,failedAssets:[],workerVersion:null,cachedCount:0,shellCount:0,missingCached:[]};
  try{
    const secure=!!(window.isSecureContext||location.protocol==='https:'||location.hostname==='localhost'||location.hostname==='127.0.0.1');
    v247AddCheck(report,'Secure context',secure?'pass':'fail',secure?`${location.protocol}//${location.host}`:'HTTPS is required for PWA installation');
    const swSupport='serviceWorker' in navigator;
    v247AddCheck(report,'Service worker support',swSupport?'pass':'fail',swSupport?'Supported by this browser':'navigator.serviceWorker is unavailable');

    await v247ManifestDiagnostics(report);

    const swFile=await v247FetchProbe('sw.js','service-worker');
    v247AddCheck(report,'Service worker file',swFile.ok?'pass':'fail',swFile.ok?`HTTP ${swFile.status} · ${swFile.contentType||'content type unavailable'}`:(swFile.status?`HTTP ${swFile.status}`:swFile.error));

    let reg=null;
    if(swSupport&&secure){
      try{reg=await v247WithTimeout(v247GetRegistration(),V247_PWA_TIMEOUT,'service worker registration');}catch(err){V244_PWA_STATE.error=String(err?.message||err);}
    }
    const hasReg=!!reg;
    v247AddCheck(report,'Service worker registration',hasReg?'pass':'fail',hasReg?`Scope: ${reg.scope}`:(V244_PWA_STATE.error||'No registration')); 
    if(reg){
      const lifecycle=reg.waiting?'waiting update':reg.active?.state||reg.installing?.state||'registered';
      v247AddCheck(report,'Worker lifecycle',reg.active||reg.waiting?'pass':'warn',lifecycle);
      const controlled=!!navigator.serviceWorker.controller;
      v247AddCheck(report,'Page controlled by worker',controlled?'pass':'warn',controlled?'Yes':'Not yet — a first successful registration may need one reload');
      const swDiag=await v247GetWorkerDiagnostics(reg);
      report.workerDiagnostics=swDiag;
      if(swDiag&&!swDiag.unsupported){
        report.workerVersion=swDiag.version??null;
        report.cachedCount=Number(swDiag.cachedCount)||0;
        report.shellCount=Number(swDiag.shellCount)||0;
        report.missingCached=Array.isArray(swDiag.missingCached)?swDiag.missingCached:[];
        const cacheOk=report.shellCount>0&&report.missingCached.length===0;
        v247AddCheck(report,'App-shell cache',cacheOk?'pass':'warn',cacheOk?`${report.cachedCount}/${report.shellCount} assets cached`:`${report.cachedCount}/${report.shellCount} cached · ${report.missingCached.length} missing; Repair app cache can retry them`);

        const shell=Array.isArray(swDiag.appShell)?swDiag.appShell:[];
        if(shell.length){
          const probes=await v247MapLimit(shell,6,asset=>v247FetchProbe(asset,'app-shell'));
          report.assetProbes=probes;
          report.failedAssets=probes.filter(x=>!x.ok).map(x=>({url:x.url,status:x.status||0,error:x.error||''}));
          v247AddCheck(report,'Deployed app-shell URLs',report.failedAssets.length?'fail':'pass',report.failedAssets.length?`${report.failedAssets.length}/${shell.length} URLs failed`: `${shell.length}/${shell.length} URLs reachable`);
        }
      }else{
        v247AddCheck(report,'Worker diagnostics','warn',swDiag?.error?'Current worker does not expose v247 diagnostics yet — apply/reload the v247 update first':'No worker diagnostic response');
      }
    }

    const installed=v244PwaStandalone()||V244_PWA_STATE.installed;
    const prompt=!!V244_PWA_STATE.installPrompt;
    v247AddCheck(report,'Native install prompt',installed||prompt?'pass':'warn',installed?'Already installed':prompt?'Browser install prompt is available':'Browser has not exposed beforeinstallprompt. This can be normal on unsupported browsers, after dismissal, or while Chrome still considers a prerequisite unmet.');

    report.finishedAt=Date.now();
    report.status=report.failures?'fail':report.warnings?'warn':'pass';
    report.summary=report.failures?`${report.failures} failed check${report.failures===1?'':'s'}`:report.warnings?`${report.warnings} warning${report.warnings===1?'':'s'}`:'all PWA checks passed';
    V247_PWA_DIAGNOSTICS.report=report;
    V247_PWA_DIAGNOSTICS.lastRunAt=report.finishedAt;
    if(!options.silent){
      try{showToast(report.status==='fail'?`PWA test found ${report.failures} problem${report.failures===1?'':'s'}`:report.status==='warn'?'PWA test passed with warnings':'PWA test passed');}catch(_){ }
    }
    const details=document.getElementById('v247-pwa-diagnostics');
    if(details&&(options.expand!==false||report.status==='fail'))details.open=true;
    return report;
  }catch(err){
    V247_PWA_DIAGNOSTICS.error=String(err?.message||err||'PWA diagnostic failed');
    report.finishedAt=Date.now();report.status='fail';report.summary='diagnostic runner failed';report.failures++;
    V247_PWA_DIAGNOSTICS.report=report;
    if(!options.silent){try{showToast('PWA diagnostics could not finish');}catch(_){ }}
    return report;
  }finally{
    V247_PWA_DIAGNOSTICS.running=false;
    v244RefreshPwaDom();
  }
}

async function v247RepairPwaCache(){
  if(V247_PWA_DIAGNOSTICS.running)return false;
  V247_PWA_DIAGNOSTICS.running=true;V247_PWA_DIAGNOSTICS.error='';v244RefreshPwaDom();
  try{
    const reg=await v247GetRegistration();
    if(!reg)throw new Error('No service worker registration is available');
    await reg.update().catch(()=>{});
    const worker=reg.waiting||reg.active||reg.installing||navigator.serviceWorker.controller;
    const result=await v247WorkerMessage(worker,{type:'RETRY_APP_SHELL_CACHE'},15000);
    if(result?.unsupported)throw new Error(result.error||'The active worker does not support cache repair yet');
    try{showToast(result?.missingCached?.length?`Cache repair finished · ${result.missingCached.length} asset${result.missingCached.length===1?'':'s'} still missing`:'MediaFlow app cache repaired');}catch(_){ }
    return result;
  }catch(err){
    V247_PWA_DIAGNOSTICS.error=String(err?.message||err||'cache repair failed');
    try{showToast('Could not repair the PWA app cache');}catch(_){ }
    return false;
  }finally{
    V247_PWA_DIAGNOSTICS.running=false;
    await v247RunPwaDiagnostics({silent:true,expand:true});
  }
}

const v247InstallPwaBase=v244InstallPwa;
v244InstallPwa=async function(){
  if(v244PwaStandalone()||V244_PWA_STATE.installed)return v247InstallPwaBase.apply(this,arguments);
  if(V244_PWA_STATE.installPrompt)return v247InstallPwaBase.apply(this,arguments);
  await v244RegisterPwa().catch(()=>null);
  if(V244_PWA_STATE.installPrompt)return v247InstallPwaBase.apply(this,arguments);
  const report=await v247RunPwaDiagnostics({silent:true,expand:true});
  if(report?.status==='fail'){
    try{showToast(`Install blocked by ${report.failures} PWA check${report.failures===1?'':'s'} · see PWA Diagnostics`);}catch(_){ }
    const details=document.getElementById('v247-pwa-diagnostics');if(details)details.open=true;
    return false;
  }
  v246PwaInstallHelp();
  return false;
};

