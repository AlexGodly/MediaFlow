function v247DiagBadge(status,text){
  return `<span class="v247-diag-badge is-${status}">${escapeHtml(text)}</span>`;
}
function v247DiagMark(status){
  if(status==='pass')return '✓';
  if(status==='fail')return '×';
  if(status==='warn')return '!';
  return '•';
}
function v247DiagRows(report){
  if(!report)return '<div class="v247-diag-empty">Run the test to verify the live PWA manifest, service worker, cache, icons and every local app-shell asset.</div>';
  return (report.checks||[]).map(row=>`<div class="v247-diag-row is-${row.status}">
    <span class="v247-diag-mark" aria-hidden="true">${v247DiagMark(row.status)}</span>
    <div class="v247-diag-copy"><b>${escapeHtml(row.label)}</b><span>${escapeHtml(row.detail||'')}</span></div>
  </div>`).join('');
}
function v247DiagFailures(report){
  const failed=report?.failedAssets||[];
  if(!failed.length)return '';
  return `<div class="v247-diag-failures"><b>Failed deployed assets</b>${failed.map(item=>`<code>${escapeHtml(item.url||item.asset||'unknown')} — ${escapeHtml(String(item.status||item.error||'failed'))}</code>`).join('')}</div>`;
}
