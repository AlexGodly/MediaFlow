function scopedRequest(url,cacheMode='reload'){
  const absolute=new URL(url,self.registration.scope);
  return new Request(absolute,{cache:cacheMode,credentials:'same-origin'});
}

async function cacheOne(cache,url){
  try{
    const request=scopedRequest(url,'reload');
    const response=await fetch(request);
    if(!response||!response.ok)throw new Error(`HTTP ${response?.status||0}`);
    await cache.put(request,response.clone());
    return {url,ok:true,status:response.status};
  }catch(err){
    return {url,ok:false,status:0,error:String(err?.message||err||'cache failed')};
  }
}

async function cacheShellAssets(urls=APP_SHELL){
  const cache=await caches.open(SHELL_CACHE);
  // Limit concurrent cache writes on low-memory Android browsers. A several-
  // hundred-asset Promise.all could saturate connections and kill the worker.
  const normalized=new Array(urls.length);
  let next=0;
  async function worker(){
    while(next<urls.length){
      const i=next++;
      try{normalized[i]=await cacheOne(cache,urls[i]);}
      catch(err){normalized[i]={url:urls[i],ok:false,status:0,error:String(err?.message||err)};}
    }
  }
  await Promise.all(Array.from({length:Math.min(8,urls.length)},()=>worker()));
  return {
    ok:normalized.every(x=>x.ok),
    cached:normalized.filter(x=>x.ok).map(x=>x.url),
    failed:normalized.filter(x=>!x.ok)
  };
}

async function shellDiagnostics(){
  const cache=await caches.open(SHELL_CACHE);
  const missingCached=[];
  let cachedCount=0;
  for(const url of APP_SHELL){
    try{
      const hit=await cache.match(scopedRequest(url,'default'));
      if(hit)cachedCount++;
      else missingCached.push(url);
    }catch(_){
      missingCached.push(url);
    }
  }
  return {
    type:'MEDIAFLOW_SW_DIAGNOSTICS',
    version:MEDIAFLOW_VERSION,
    cacheName:SHELL_CACHE,
    shellCount:APP_SHELL.length,
    cachedCount,
    missingCached,
    appShell:[...APP_SHELL]
  };
}

function replyMessage(event,payload){
  try{
    if(event.ports&&event.ports[0])event.ports[0].postMessage(payload);
    else event.source?.postMessage(payload);
  }catch(_){ }
}

self.addEventListener('install',event=>{
  // A long 244-file pre-cache previously kept new versions waiting for minutes
  // (or indefinitely on weak mobile connections). Install only critical files.
  event.waitUntil((async()=>{
    const critical=APP_SHELL.filter(url=>url==='./index.html'||
      (url.includes('/assets/js/mediaflow-v')&&url.endsWith('.bundle.js'))||
      url==='./version.json');
        try{await cacheShellAssets(critical);}catch(err){
      console.warn('[MediaFlow PWA] critical shell cache incomplete',err);
    }
    await self.skipWaiting();
  })());
});

self.addEventListener('activate',event=>{
  event.waitUntil((async()=>{
    // Claim immediately; noncritical assets cache lazily as requested.
    await self.clients.claim();
    const clients=await self.clients.matchAll({type:'window',includeUncontrolled:true});
    clients.forEach(client=>client.postMessage({type:'MEDIAFLOW_SW_ACTIVATED',version:MEDIAFLOW_VERSION}));
    // Do not block activation on 244 remote fetches.
    const keys=await caches.keys();
    await Promise.all(keys.filter(key=>
      (key.startsWith(CACHE_PREFIX)||key.startsWith('mediaflow-v'))&&key!==SHELL_CACHE
    ).map(key=>caches.delete(key)));
  })());
});

self.addEventListener('message',event=>{
  const type=event.data?.type;

  if(type==='SKIP_WAITING'){
    self.skipWaiting();
    return;
  }

  if(type==='GET_VERSION'){
    replyMessage(event,{type:'MEDIAFLOW_SW_VERSION',version:MEDIAFLOW_VERSION});
    return;
  }

  if(type==='GET_DIAGNOSTICS'){
    event.waitUntil((async()=>{
      try{
        replyMessage(event,await shellDiagnostics());
      }catch(err){
        replyMessage(event,{
          type:'MEDIAFLOW_SW_DIAGNOSTICS',
          version:MEDIAFLOW_VERSION,
          error:String(err?.message||err)
        });
      }
    })());
    return;
  }

  if(type==='RETRY_APP_SHELL_CACHE'){
    event.waitUntil((async()=>{
      try{
        const before=await shellDiagnostics();
        const retried=await cacheShellAssets(before.missingCached.length?before.missingCached:APP_SHELL);
        const after=await shellDiagnostics();
        replyMessage(event,{
          ...after,
          type:'MEDIAFLOW_SW_CACHE_RESULT',
          version:MEDIAFLOW_VERSION,
          retried
        });
      }catch(err){
        replyMessage(event,{
          type:'MEDIAFLOW_SW_CACHE_RESULT',
          version:MEDIAFLOW_VERSION,
          error:String(err?.message||err)
        });
      }
    })());
  }
});

function isAppDocument(url){
  return url.origin===APP_SCOPE_URL.origin&&
    (url.pathname===APP_SCOPE_URL.pathname||url.pathname===APP_INDEX_URL.pathname);
}

async function networkFirst(request,fallbackUrl){
  const cache=await caches.open(SHELL_CACHE);
  try{
    // v522: bypass the HTTP disk cache so installed apps cannot reload stale HTML/version metadata.
    const response=await fetch(request,{cache:'reload'});
    if(response&&response.ok)eventualPut(cache,request,response.clone());
    return response;
  }catch(err){
    const cached=await cache.match(request);
    if(cached)return cached;
    if(fallbackUrl){
      const fallbackRequest=scopedRequest(fallbackUrl,'default');
      const fallback=await cache.match(fallbackRequest);
      if(fallback)return fallback;
      // During a partial upgrade retain the previous version's offline page.
      const older=await caches.match(fallbackRequest);
      if(older)return older;
    }
    const older=await caches.match(request);
    if(older)return older;
    throw err;
  }
}

function eventualPut(cache,request,response){
  Promise.resolve(cache.put(request,response)).catch(()=>{});
}

async function cacheFirst(request){
  const cache=await caches.open(SHELL_CACHE);
  const cached=await cache.match(request);
  if(cached)return cached;
  try{
    const response=await fetch(request);
    if(response&&response.ok)eventualPut(cache,request,response.clone());
    return response;
  }catch(err){
    const older=await caches.match(request);
    if(older)return older;
    throw err;
  }
}

self.addEventListener('fetch',event=>{
  const request=event.request;
  if(request.method!=='GET')return;
  const url=new URL(request.url);
  if(url.origin!==self.location.origin)return;

  if(request.mode==='navigate'||isAppDocument(url)){
    event.respondWith(networkFirst(request,'./index.html'));
    return;
  }

  if(url.pathname===VERSION_URL.pathname||url.pathname===MANIFEST_URL.pathname||url.pathname===WORKER_URL.pathname){
    event.respondWith(networkFirst(request));
    return;
  }

  const scopePath=APP_SCOPE_URL.pathname;
  const relative='./'+url.pathname.slice(scopePath.length);
  if(APP_SHELL.includes(relative)){
    event.respondWith(cacheFirst(request));
  }
});
